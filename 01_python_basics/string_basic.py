first_name = "Rajeev"
last_name = "Subedi"
print(first_name)
print(type(first_name))
print(last_name)
print(type(last_name))

#Joining strings
full_name = first_name + "" + last_name

#Length
print(len(full_name))

#Change Case
print(full_name.upper())
print(full_name.lower())
print(full_name.title())

#Access characters
print(full_name[0])
print(full_name[-1])

#Slicing
print(full_name[0:6])
